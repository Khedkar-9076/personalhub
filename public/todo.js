const $ = id => document.getElementById(id);

const STORAGE_KEY = "taskflow_personal_planner_v1";
const THEME_KEY = "taskflow_theme";

let tasks = [];
let activeFilter = "all";
let activeCategory = "all";

try {
  const saved = JSON.parse(localStorage.getItem(STORAGE_KEY) || "[]");
  tasks = Array.isArray(saved) ? saved : [];
} catch {
  tasks = [];
}

function saveTasks() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(tasks));
}

function todayString() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

function escapeHTML(value = "") {
  return String(value).replace(/[&<>"']/g, ch => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;",
    '"': "&quot;", "'": "&#39;"
  })[ch]);
}

function formatDate(value) {
  if (!value) return "No due date";
  const [y, m, d] = value.split("-").map(Number);
  return new Date(y, m - 1, d).toLocaleDateString("en-IN", {
    day: "numeric", month: "short", year: "numeric"
  });
}

function isOverdue(task) {
  return !task.completed && task.dueDate && task.dueDate < todayString();
}

function isToday(task) {
  return task.dueDate === todayString();
}

function priorityRank(priority) {
  return { high: 0, medium: 1, low: 2 }[priority] ?? 1;
}

function openModal(task = null) {
  $("task-form").reset();
  $("task-id").value = task?.id || "";
  $("task-title").value = task?.title || "";
  $("task-desc").value = task?.description || "";
  $("task-category").value = task?.category || "Study";
  $("task-priority").value = task?.priority || "medium";
  $("task-due-date").value = task?.dueDate || "";
  $("task-repeat").value = task?.repeat || "none";
  $("modal-title").textContent = task ? "Edit task" : "Create a task";
  $("task-modal").classList.add("active");
  $("task-title").focus();
}

function closeModal() {
  $("task-modal").classList.remove("active");
}

$("open-modal-btn").addEventListener("click", () => openModal());
$("close-modal-btn").addEventListener("click", closeModal);
$("cancel-modal-btn").addEventListener("click", closeModal);

$("task-modal").addEventListener("click", e => {
  if (e.target === $("task-modal")) closeModal();
});

document.addEventListener("keydown", e => {
  if (e.key === "Escape") closeModal();
});


$("task-form").addEventListener("submit", async e => {
  e.preventDefault();

  const id = $("task-id").value;
  const existing = tasks.find(t => String(t.id) === id);

  const task = {
    id: id || "",
    title: $("task-title").value.trim(),
    description: $("task-desc").value.trim(),
    category: $("task-category").value,
    priority: $("task-priority").value,
    dueDate: $("task-due-date").value,
    repeat: $("task-repeat").value,
    completed: existing?.completed || false,
    createdAt: existing?.createdAt || new Date().toISOString()
  };

  if (!task.title) return;

  // Existing task edit: currently localStorage only
  if (existing) {
    tasks = tasks.map(t =>
      String(t.id) === id ? { ...task, id: existing.id } : t
    );

    saveTasks();
    closeModal();
    render();
    return;
  }

  // New task: save to MySQL through Express API
  try {
    const response = await fetch("/api/tasks", {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        title: task.title,
        description: task.description,
        category: task.category,
        priority: task.priority,
        dueDate: task.dueDate || ""
      })
    });

    const result = await response.json();

    if (!response.ok) {
      throw new Error(result.error || "Task save failed");
    }

    // Use the ID generated by MySQL
    task.id = String(result.id);

    tasks.unshift(task);
    saveTasks();
    closeModal();
    render();

    console.log("MySQL save success:", result);
    alert("Task MySQL save ✅");

  } catch (error) {
    console.error("Task save error:", error.message);
    alert("Task not save: " + error.message);
  }
});

function toggleTask(id) {
  const task = tasks.find(t => t.id === id);
  if (!task) return;

  const completing = !task.completed;
  task.completed = completing;

  // Create the next occurrence when a recurring task is completed.
  if (completing && task.repeat !== "none" && task.dueDate) {
    const next = new Date(`${task.dueDate}T12:00:00`);
    next.setDate(next.getDate() + (task.repeat === "daily" ? 1 : 7));

    const nextDate =
      `${next.getFullYear()}-${String(next.getMonth() + 1).padStart(2, "0")}-${String(next.getDate()).padStart(2, "0")}`;

    tasks.unshift({
      ...task,
      id: crypto.randomUUID ? crypto.randomUUID() : `${Date.now()}-${Math.random()}`,
      dueDate: nextDate,
      completed: false,
      createdAt: new Date().toISOString()
    });
  }

  saveTasks();
  render();
}

async function deleteTask(id) {
    alert("Delete clicked! ID: " + id);
    try {
        const task = tasks.find(t => String(t.id) === String(id));

        if (!task) {
            console.error("Task not found:", id);
            return;
        }

        const response = await fetch(`/api/tasks/${task.id}`, {
            method: "DELETE"
        });

        const result = await response.json();

        if (!response.ok) {
            throw new Error(result.error || "Delete failed");
        }

        tasks = tasks.filter(t => String(t.id) !== String(id));

        saveTasks();
        render();

        console.log("Task deleted successfully:", task.id);

    } catch (error) {
        console.error("Delete error:", error.message);
        alert("Task delete झाले नाही: " + error.message);
    }
}


function getVisibleTasks() {
  const query = $("search-input").value.trim().toLowerCase();

  let result = tasks.filter(task => {
    const matchesSearch =
      `${task.title} ${task.description || ""} ${task.category}`.toLowerCase().includes(query);

    const matchesCategory =
      activeCategory === "all" || task.category === activeCategory;

    let matchesFilter = true;

    if (activeFilter === "today") matchesFilter = isToday(task);
    if (activeFilter === "pending") matchesFilter = !task.completed;
    if (activeFilter === "completed") matchesFilter = task.completed;
    if (activeFilter === "overdue") matchesFilter = Boolean(isOverdue(task));

    return matchesSearch && matchesCategory && matchesFilter;
  });

  const sort = $("sort-select").value;

  result.sort((a, b) => {
    if (sort === "title") return a.title.localeCompare(b.title);
    if (sort === "priority") return priorityRank(a.priority) - priorityRank(b.priority);

    if (sort === "date-desc") {
      return (b.dueDate || "0000-00-00").localeCompare(a.dueDate || "0000-00-00");
    }

    return (a.dueDate || "9999-99-99").localeCompare(b.dueDate || "9999-99-99");
  });

  return result;
}

function renderTasks() {
  const container = $("tasks-container");
  const visible = getVisibleTasks();

  const names = {
    all: "All Tasks",
    today: "Today's Tasks",
    pending: "Pending Tasks",
    completed: "Completed Tasks",
    overdue: "Overdue Tasks"
  };

  $("current-view-title").textContent = names[activeFilter];

  if (!visible.length) {
    container.innerHTML = `
      <div class="empty-state">
        <i class="fa-solid fa-cloud-sun"></i>
        <h3>No tasks found 🌷</h3>
        <p>Add a new task or try a different filter.</p>
      </div>`;
    return;
  }
  // Handle Edit and Delete button clicks
$("tasks-container").addEventListener("click", (e) => {
    const button = e.target.closest("button[data-action]");

    if (!button) return;

    const action = button.dataset.action;
    const id = button.dataset.id;

    if (action === "delete") {
        deleteTask(id);
    }

    if (action === "edit") {
        const task = tasks.find(
            t => String(t.id) === String(id)
        );

        if (task) {
            openModal(task);
        }
    }
});

  container.innerHTML = visible.map(task => {
    const dueClass = isOverdue(task) ? "due-overdue" : "";
    const dueLabel = isOverdue(task) ? "Overdue" : formatDate(task.dueDate);

    return `
      <article class="task-card ${task.completed ? "completed" : ""}">
        <input class="task-checkbox" type="checkbox"
          data-action="toggle" data-id="${escapeHTML(task.id)}"
          aria-label="Mark ${escapeHTML(task.title)} complete"
          ${task.completed ? "checked" : ""}>

        <div class="task-body">
          <div class="task-meta-top">
            <span class="task-title">${escapeHTML(task.title)}</span>
            <span class="badge-cat">${escapeHTML(task.category)}</span>
            <span class="badge-priority priority-${escapeHTML(task.priority)}">
              ${escapeHTML(task.priority)}
            </span>
          </div>

          ${task.description
            ? `<p class="task-desc">${escapeHTML(task.description)}</p>`
            : ""}

          <div class="task-footer-info">
            <span class="${dueClass}">
              <i class="fa-regular fa-calendar"></i>
              ${escapeHTML(dueLabel)}
            </span>
            ${task.repeat !== "none"
              ? `<span><i class="fa-solid fa-repeat"></i> ${task.repeat === "daily" ? "Daily" : "Weekly"}</span>`
              : ""}
            ${task.completed
              ? `<span><i class="fa-solid fa-circle-check"></i> Completed</span>`
              : ""}
          </div>
        </div>

        <div class="task-actions">
          <button class="action-btn" data-action="edit" data-id="${escapeHTML(task.id)}"
            aria-label="Edit task" title="Edit">
            <i class="fa-regular fa-pen-to-square"></i>
          </button>
          <button class="action-btn delete" data-action="delete" data-id="${escapeHTML(task.id)}"
            aria-label="Delete task" title="Delete">
            <i class="fa-regular fa-trash-can"></i>
          </button>
        </div>
      </article>`;
  }).join("");
}

function renderStats() {
  const total = tasks.length;
  const completed = tasks.filter(t => t.completed).length;
  const pending = tasks.filter(t => !t.completed).length;
  const overdue = tasks.filter(isOverdue).length;
  const todayTasks = tasks.filter(isToday);
  const todayCompleted = todayTasks.filter(t => t.completed).length;

  $("count-all").textContent = total;
  $("count-today").textContent = todayTasks.length;
  $("count-pending").textContent = pending;
  $("count-completed").textContent = completed;
  $("count-overdue").textContent = overdue;

  $("stat-total").textContent = total;
  $("stat-completed").textContent = completed;
  $("stat-pending").textContent = pending;
  $("stat-overdue").textContent = overdue;

  const percent = todayTasks.length
    ? Math.round(todayCompleted / todayTasks.length * 100)
    : 0;

  $("progress-text").textContent =
    `${todayCompleted} of ${todayTasks.length} tasks completed today`;
  $("progress-percent").textContent = `${percent}%`;
  $("progress-bar").style.width = `${percent}%`;
}

function render() {
  renderStats();
  renderTasks();
}

async function loadTasksFromMySQL() {
    try {
        const response = await fetch("/api/tasks");
        const result = await response.json();

        if (!response.ok) {
            throw new Error(result.error || "Tasks load failed");
        }

        // API should return an array of tasks
        const rows = Array.isArray(result)
            ? result
            : result.tasks;

        if (!Array.isArray(rows)) {
            throw new Error("Invalid tasks response");
        }

        // Convert MySQL rows into the format used by todo.js
        tasks = rows.map(row => ({
            id: String(row.id),
            title: row.title || "",
            description: row.description || "",
            category: row.category || "Study",
            priority: row.priority || "medium",
            dueDate: row.dueDate || row.due_date || "",
            repeat: row.repeat || "none",
            completed:
                row.completed === true ||
                row.completed === 1 ||
                row.completed === "1",
            createdAt: row.createdAt ||
                row.created_at ||
                new Date().toISOString()
        }));

        // Keep a local copy for offline fallback
        saveTasks();
        render();

        console.log("Tasks loaded from MySQL:", tasks.length);

    } catch (error) {
        console.error("MySQL load error:", error.message);

        // Show previously saved localStorage tasks if API fails
        render();
    }
}


$("tasks-container").addEventListener("change", async (e) => {
    const checkbox = e.target;

    if (!checkbox.matches('input[data-action="toggle"]')) {
        return;
    }

    const id = checkbox.dataset.id;
    const completed = checkbox.checked;

    try {
        const response = await fetch(
            `/api/tasks/${encodeURIComponent(id)}/complete`,
            {
                method: "PATCH",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify({ completed })
            }
        );

        const result = await response.json();

        if (!response.ok) {
            throw new Error(result.error || "Update failed");
        }

        const task = tasks.find(
            t => String(t.id) === String(id)
        );

        if (task) {
            task.completed = completed;
            saveTasks();
            render();
        }

        console.log("MySQL completed status:", result.completed);

    } catch (error) {
        checkbox.checked = !completed;
        console.error("Complete update error:", error.message);
        alert("MySQL मध्ये status update झाला नाही: " + error.message);
    }
});
